// Rerunnable: book/gateless-gate.md -> src/koans/text/mumonkan.js + matter.js
// Run: node scripts/build-text.js
//
// The book's text used to live in two files in local/, which is gitignored: a
// plain-text rendering of the forty-nine cases and a 60 KB scholarly working
// document holding the front and back matter among its Chinese, its citations
// and its notes. A fresh clone could run the site and never rebuild its text.
// Both are now one checked-in Markdown file and one parser.
//
// book/gateless-gate.md was itself generated from the modules this script now
// writes — scripts/dev/write-book-source.js, 2026-08-11, deleted after the one
// run — and was accepted only after parsing back to them exactly.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseBook, CASE_COUNT } from './lib/parse-book.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcFile = path.join(root, 'book', 'gateless-gate.md');
const outFile = path.join(root, 'src', 'koans', 'text', 'mumonkan.js');
const outMatter = path.join(root, 'src', 'koans', 'text', 'matter.js');

if (!fs.existsSync(srcFile)) {
  console.error(`\nBUILD FAILED: ${srcFile} is missing.`);
  process.exit(1);
}

// Hand-fixes for anything the uniform rules misparse (id -> partial entry).
// Empty, and now much likelier to stay so: the source names every section
// rather than leaving the parser to infer where one ends.
const OVERRIDES = {};

const { cases, matter } = parseBook(fs.readFileSync(srcFile, 'utf8'));
for (const [id, patch] of Object.entries(OVERRIDES)) cases[id] = { ...cases[id], ...patch };

const ids = Object.keys(cases).map(Number).sort((a, b) => a - b);
console.log('id  verse-len  case-len  comment-len  title');
for (const id of ids) {
  const c = cases[id];
  console.log(
    String(id).padStart(2), String(c.verse.length).padStart(9), String(c.case.length).padStart(8),
    String(c.comment.length).padStart(11), ' ', c.title,
  );
}
if (ids.length !== CASE_COUNT) {
  console.error(`\nBUILD FAILED: expected ${CASE_COUNT} entries, got ${ids.length}`);
  process.exit(1);
}

const body = ids.map((id) => `  ${id}: ${JSON.stringify(cases[id])},`).join('\n');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `// GENERATED by scripts/build-text.js from book/gateless-gate.md — do not edit by hand.
export default {
${body}
};
`);
console.log(`\nWrote ${outFile} (${ids.length} cases).`);

// Its own module, never folded into mumonkan.js: build-narration.js re-bakes
// any unit whose text hash changed, so keeping the two apart makes it
// impossible for a preface edit to cost 147 files of TTS.
for (const [slug, p] of Object.entries(matter)) {
  console.log(`${slug}: ${p.sections.map((k) => `${k} ${p.text[k].length}`).join(', ')}`);
}
fs.writeFileSync(outMatter, `// GENERATED by scripts/build-text.js from book/gateless-gate.md — do not edit by hand.
export default ${JSON.stringify(matter, null, 2)};
`);
console.log(`Wrote ${outMatter} (${Object.keys(matter).length} pages).`);
